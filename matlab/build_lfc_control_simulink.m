function simResult = build_lfc_control_simulink(projectDir, p, controllers)
%BUILD_LFC_CONTROL_SIMULINK Build and run a three-branch LFC comparison.
%   simResult = build_lfc_control_simulink(projectDir,p,controllers) writes
%   model/lfc_control_comparison.slx below projectDir. The saved model contains
%   numerical block parameters and needs no variables in the base workspace.
%
%   p requires Tg, Tt, Tp, Ksys, R, loadStep, stepTime, and tEnd.
%   controllers contains two structures with name, Kp, Ki, Kd, and Tf.
%   The intended order is PI, followed by filtered PID.
%   Each controller uses C(s) = Kp + Ki/s + Kd*s/(Tf*s+1).
%
%   All branches retain explicit primary droop. Secondary control is
%   u = -C(s)*df, while the governor receives u - df/R.
%   The load disturbance enters negatively before the generator/load block.
%   All dynamic states start at zero deviation. This model has no saturation.
%
%   simResult has three elements. Each contains name, t, df, and u.
%   t is in seconds, df is in Hz, and u is in per-unit power.

    narginchk(3, 3);
    validateattributes(projectDir, {'char','string'}, {'nonempty'}, ...
        mfilename, 'projectDir');
    if isstring(projectDir)
        assert(isscalar(projectDir), 'LFC:ProjectDirectory', ...
            'projectDir must be a scalar string or character row.');
    else
        assert(isrow(projectDir), 'LFC:ProjectDirectory', ...
            'projectDir must be a scalar string or character row.');
    end
    projectDir = char(projectDir);
    validateattributes(p, {'struct'}, {'scalar'}, mfilename, 'p');
    positiveFields = {'Tg','Tt','Tp','Ksys','R','tEnd'};
    for k = 1:numel(positiveFields)
        field = positiveFields{k};
        assert(isfield(p,field), 'LFC:MissingParameter', ...
            'Missing parameter p.%s.', field);
        validateattributes(p.(field), {'numeric'}, ...
            {'real','finite','scalar','positive'}, mfilename, ['p.' field]);
    end
    validateattributes(p.loadStep, {'numeric'}, ...
        {'real','finite','scalar'}, mfilename, 'p.loadStep');
    validateattributes(p.stepTime, {'numeric'}, ...
        {'real','finite','scalar','nonnegative','<',p.tEnd}, ...
        mfilename, 'p.stepTime');
    assert(isstruct(controllers) && numel(controllers) == 2, ...
        'LFC:ControllerCount', 'Provide two controller structures: PI and PID.');
    requiredFields = {'name','Kp','Ki','Kd','Tf'};
    for i = 1:2
        for k = 1:numel(requiredFields)
            assert(isfield(controllers(i),requiredFields{k}), ...
                'LFC:ControllerField', 'Controller %d lacks field %s.', ...
                i, requiredFields{k});
        end
        validateattributes(controllers(i).name, {'char','string'}, ...
            {'nonempty'}, mfilename, sprintf('controllers(%d).name',i));
        assert((ischar(controllers(i).name) && isrow(controllers(i).name)) || ...
            (isstring(controllers(i).name) && isscalar(controllers(i).name)), ...
            'LFC:ControllerName', 'Controller names must be text scalars.');
        for field = {'Kp','Ki','Kd','Tf'}
            validateattributes(controllers(i).(field{1}), {'numeric'}, ...
                {'real','finite','scalar','nonnegative'}, mfilename, ...
                sprintf('controllers(%d).%s',i,field{1}));
        end
        assert(controllers(i).Ki > 0, 'LFC:IntegralGain', ...
            'Both secondary controllers must have a positive integral gain.');
        assert(controllers(i).Kd == 0 || controllers(i).Tf > 0, ...
            'LFC:DerivativeFilter', ...
            'A nonzero derivative gain requires a positive filter time.');
    end

    modelDir = fullfile(projectDir,'model');
    if ~isfolder(modelDir), mkdir(modelDir); end
    model = 'lfc_control_comparison';
    modelFile = fullfile(modelDir,[model '.slx']);
    if bdIsLoaded(model)
        loadedFile = get_param(model,'FileName');
        if ~strcmp(loadedFile,modelFile) || strcmp(get_param(model,'Dirty'),'on')
            error('LFC:ModelAlreadyLoaded', ...
                ['The model %s is loaded from another location or has ' ...
                 'unsaved changes. Save or close that model first.'],model);
        end
        close_system(model,0);
    end

    load_system('simulink');
    new_system(model);
    number = @(value) sprintf('%.17g',value);
    set_param(model, ...
        'SolverType','Variable-step', 'Solver','ode45', ...
        'MaxStep','0.005', 'RelTol','1e-9', 'AbsTol','1e-11', ...
        'StartTime','0', 'StopTime',number(p.tEnd), ...
        'ReturnWorkspaceOutputs','on', 'SaveTime','on', ...
        'TimeSaveName','tout', 'SaveOutput','off', 'SignalLogging','off');

    add_block('simulink/Sources/Step',[model '/Common load disturbance'], ...
        'Time',number(p.stepTime), 'Before','0', ...
        'After',number(p.loadStep), 'SampleTime','0', ...
        'Position',[45 325 105 365]);
    add_block('simulink/Sinks/Scope',[model '/Frequency comparison'], ...
        'NumInputPorts','3', 'Position',[1090 185 1155 255]);
    add_block('simulink/Sinks/Scope',[model '/Secondary control comparison'], ...
        'NumInputPorts','3', 'Position',[1090 470 1155 540]);

    branchNames = {'Primary droop only','PI secondary control', ...
        'Filtered PID secondary control'};
    resultNames = {'Primary droop only',char(controllers(1).name), ...
        char(controllers(2).name)};
    logSuffixes = {'primary','pi','pid'};
    for i = 1:3
        yTop = 110 + (i-1)*220;
        subsystem = [model '/' branchNames{i}];
        add_block('built-in/Subsystem',subsystem, ...
            'Position',[285 yTop 625 yTop+120]);
        if i == 1
            buildBranch(subsystem,p,[],resultNames{i});
        else
            buildBranch(subsystem,p,controllers(i-1),resultNames{i});
        end
        loadLine = add_line(model,'Common load disturbance/1', ...
            [branchNames{i} '/1'],'autorouting','on');
        if i == 1, set_param(loadLine,'Name','Delta PL (pu)'); end

        frequencyLogName = ['Frequency log ' logSuffixes{i}];
        controlLogName = ['Control log ' logSuffixes{i}];
        add_block('simulink/Sinks/To Workspace',[model '/' frequencyLogName], ...
            'VariableName',['lfc_df_' logSuffixes{i}], ...
            'SaveFormat','Timeseries','MaxDataPoints','inf', ...
            'Decimation','1','SampleTime','-1', ...
            'Position',[755 yTop+5 930 yTop+40]);
        add_block('simulink/Sinks/To Workspace',[model '/' controlLogName], ...
            'VariableName',['lfc_u_' logSuffixes{i}], ...
            'SaveFormat','Timeseries','MaxDataPoints','inf', ...
            'Decimation','1','SampleTime','-1', ...
            'Position',[755 yTop+75 930 yTop+110]);
        frequencyLine = add_line(model,[branchNames{i} '/1'], ...
            [frequencyLogName '/1'],'autorouting','on');
        set_param(frequencyLine,'Name',[resultNames{i} ': df (Hz)']);
        controlLine = add_line(model,[branchNames{i} '/2'], ...
            [controlLogName '/1'],'autorouting','on');
        set_param(controlLine,'Name',[resultNames{i} ': u (pu)']);
        add_line(model,[branchNames{i} '/1'], ...
            sprintf('Frequency comparison/%d',i),'autorouting','on');
        add_line(model,[branchNames{i} '/2'], ...
            sprintf('Secondary control comparison/%d',i),'autorouting','on');
    end

    titleNote = Simulink.Annotation(model, ...
        'Single-area LFC: primary droop, PI and filtered PID');
    titleNote.Position = [45 25]; titleNote.FontSize = 16;
    caseNote = Simulink.Annotation(model,sprintf( ...
        ['Shared load increase: %.5g pu at t = %.5g s. ' ...
         'All initial deviations are zero.\n' ...
         'Open each branch to inspect the governor, turbine, ' ...
         'generator/load and explicit droop feedback.\n' ...
         'This linear comparison has no saturation. ' ...
         'Numerical parameters are stored directly in every block.'], ...
        p.loadStep,p.stepTime));
    caseNote.Position = [45 735]; caseNote.FontSize = 11;
    set_param(model,'SimulationCommand','update');
    set_param(model,'ZoomFactor','FitSystem');
    save_system(model,modelFile);

    simulationOutput = sim(model,'ReturnWorkspaceOutputs','on');
    simResult = repmat(struct('name','','t',[],'df',[],'u',[]),1,3);
    for i = 1:3
        frequencyLog = simulationOutput.get(['lfc_df_' logSuffixes{i}]);
        controlLog = simulationOutput.get(['lfc_u_' logSuffixes{i}]);
        time = double(frequencyLog.Time(:));
        controlTime = double(controlLog.Time(:));
        assert(isequal(size(time),size(controlTime)) && ...
            all(abs(time-controlTime) < 1e-10), 'LFC:LoggingTimes', ...
            'Frequency and control output times differ in branch %s.', ...
            resultNames{i});
        df = double(frequencyLog.Data(:));
        u = double(controlLog.Data(:));
        assert(numel(time) == numel(df) && numel(time) == numel(u) && ...
            all(isfinite(time)) && all(isfinite(df)) && all(isfinite(u)), ...
            'LFC:InvalidLoggedData', ...
            'Invalid logged data in branch %s.',resultNames{i});
        simResult(i) = struct('name',resultNames{i},'t',time,'df',df,'u',u);
    end
    save_system(model,modelFile);
    % Leave the generated model loaded. Unrelated loaded models are untouched.
end

function buildBranch(subsystem,p,controller,label)
%BUILDBRANCH Construct the explicit primary loop and optional secondary loop.
    number = @(value) sprintf('%.17g',value);
    add_block('simulink/Sources/In1',[subsystem '/Load increase'], ...
        'Port','1','Position',[460 270 490 290]);
    add_block('simulink/Sinks/Out1',[subsystem '/Frequency deviation'], ...
        'Port','1','Position',[835 175 865 195]);
    add_block('simulink/Sinks/Out1',[subsystem '/Secondary command'], ...
        'Port','2','Position',[835 285 865 305]);
    add_block('simulink/Math Operations/Sum',[subsystem '/Governor command'], ...
        'Inputs','+-','IconShape','rectangular','Position',[160 165 185 205]);
    add_block('simulink/Continuous/Transfer Fcn',[subsystem '/Governor'], ...
        'Numerator','1','Denominator',mat2str([p.Tg 1],17), ...
        'Position',[235 165 325 205]);
    add_block('simulink/Continuous/Transfer Fcn',[subsystem '/Non-reheat turbine'], ...
        'Numerator','1','Denominator',mat2str([p.Tt 1],17), ...
        'Position',[380 165 470 205]);
    add_block('simulink/Math Operations/Sum',[subsystem '/Power imbalance'], ...
        'Inputs','+-','IconShape','rectangular','Position',[520 165 545 205]);
    add_block('simulink/Continuous/Transfer Fcn',[subsystem '/Generator and load'], ...
        'Numerator',number(p.Ksys),'Denominator',mat2str([p.Tp 1],17), ...
        'Position',[600 165 710 205]);
    add_block('simulink/Math Operations/Gain',[subsystem '/Primary droop 1 over R'], ...
        'Gain',number(1/p.R),'Orientation','left', ...
        'Position',[600 355 710 395]);

    if isempty(controller)
        add_block('simulink/Sources/Constant',[subsystem '/No secondary control'], ...
            'Value','0','SampleTime','0','Position',[45 100 85 130]);
        commandSource = 'No secondary control/1';
        controllerText = 'Secondary command u = 0; primary droop remains active.';
    else
        add_block('simulink/Math Operations/Gain',[subsystem '/Error minus df'], ...
            'Gain','-1','Orientation','left','Position',[600 50 710 90]);
        if controller.Kd == 0
            numerator = [controller.Kp controller.Ki];
            denominator = [1 0];
        else
            numerator = [controller.Kp*controller.Tf+controller.Kd, ...
                controller.Kp+controller.Ki*controller.Tf,controller.Ki];
            denominator = [controller.Tf 1 0];
        end
        add_block('simulink/Continuous/Transfer Fcn', ...
            [subsystem '/Secondary controller C'], ...
            'Numerator',mat2str(numerator,17), ...
            'Denominator',mat2str(denominator,17),'Orientation','left', ...
            'Position',[280 45 460 95]);
        add_line(subsystem,'Generator and load/1','Error minus df/1', ...
            'autorouting','on');
        add_line(subsystem,'Error minus df/1','Secondary controller C/1', ...
            'autorouting','on');
        commandSource = 'Secondary controller C/1';
        controllerText = sprintf( ...
            ['C(s) = Kp + Ki/s + Kd*s/(Tf*s+1); u = -C(s)*df.\n' ...
             'Kp = %.5g, Ki = %.5g, Kd = %.5g, Tf = %.5g s.'], ...
            controller.Kp,controller.Ki,controller.Kd,controller.Tf);
    end

    commandLine = add_line(subsystem,commandSource,'Governor command/1', ...
        'autorouting','on');
    set_param(commandLine,'Name','u (pu)');
    add_line(subsystem,commandSource,'Secondary command/1','autorouting','on');
    add_line(subsystem,'Governor command/1','Governor/1','autorouting','on');
    governorLine = add_line(subsystem,'Governor/1','Non-reheat turbine/1', ...
        'autorouting','on');
    % State units are given in the annotation to avoid cramped signal labels.
    powerLine = add_line(subsystem,'Non-reheat turbine/1','Power imbalance/1', ...
        'autorouting','on');
    % Mechanical-power state is defined in the annotation.
    loadLine = add_line(subsystem,'Load increase/1','Power imbalance/2', ...
        'autorouting','on');
    set_param(loadLine,'Name','Delta PL (pu)');
    add_line(subsystem,'Power imbalance/1','Generator and load/1', ...
        'autorouting','on');
    frequencyLine = add_line(subsystem,'Generator and load/1', ...
        'Frequency deviation/1','autorouting','on');
    % Frequency port name identifies the signal without repeated branch labels.
    add_line(subsystem,'Generator and load/1','Primary droop 1 over R/1', ...
        'autorouting','on');
    droopLine = add_line(subsystem,'Primary droop 1 over R/1', ...
        'Governor command/2','autorouting','on');
    set_param(droopLine,'Name','Delta f over R (pu)');

    titleNote = Simulink.Annotation(subsystem,label);
    titleNote.Position = [35 5]; titleNote.FontSize = 14;
    explanation = Simulink.Annotation(subsystem,sprintf( ...
        ['%s\nGovernor input: u - df/R. ' ...
         'Power imbalance: Delta Pm - Delta PL.\n' ...
         'Governor output v (pu); turbine output m (pu); output df (Hz).\n' ...
         'Governor: 1/(%.5g s+1). Turbine: 1/(%.5g s+1). Positive primary gain: %.5g pu/Hz.\n' ...
         'Continuous-time transfer functions; zero initial deviations; no saturation.'], ...
        controllerText,p.Tg,p.Tt,1/p.R));
    explanation.Position = [35 440]; explanation.FontSize = 11;
    set_param(subsystem,'ZoomFactor','FitSystem');
end
